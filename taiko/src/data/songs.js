export function getSongById(songId) {
  return SONG_CATALOG.find((s) => s.id === songId) || SONG_CATALOG[0];
}

export function compileSongChart(songId, difficulty = 'normal') {
  const song = getSongById(songId);
  const diffChart = song.charts[difficulty] || song.charts.normal;
  const compiled = parseTJALiteChart({
    title: song.title,
    bpm: song.bpm,
    offsetMs: song.offsetMs,
    measures: diffChart.measures,
    balloonCounts: diffChart.balloonCounts || [],
  });
  return {
    song,
    difficulty,
    stars: diffChart.stars,
    ...compiled,
  };
}
